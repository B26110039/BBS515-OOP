public class Araç_2
{
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

String marka;
String model;
String durum;
double gunlukUcret;
boolean kiradaMi;

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
		public Araç_2(String marka, String model, double gunlukUcret, boolean kiradaMi) 
		{
		 this.marka = marka;
		 this.model = model;
		 this.gunlukUcret = gunlukUcret;
		 this.kiradaMi = kiradaMi;
		 this.durum = kiradaMi? "Kirada" : "Müsait";
		}
		///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
		void bilgileriGoster() 
		{
		 System.out.println("Marka: " + marka);
		 System.out.println("Model: " + durum);
		 System.out.println("Günlük Ücret: " + gunlukUcret + " TL");
		 System.out.println("Durum: " + durum);
		 System.out.println("-------------------- ");
		}
		///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
		void kirala()
		{
		 if (kiradaMi == false) {kiradaMi = true; System.out.println (marka + " " + model + " başarıyla kiralandı.");}
		 else {System.out.println("Bu araç zaten kiralanmış!");}
		 durum = kiradaMi ? "Kirada" : "Müsait";
		}
		///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
		void teslimEt()
		{
		 if (kiradaMi == true) {System.out.println (marka + " " + model + " başarıyla teslim alındı."); kiradaMi = false;}
		 else {System.out.println("Bu araç zaten müsait!");}
		 durum = kiradaMi ? "Kirada" : "Müsait";
		}
		///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
		double kiraBedeliHesapla (int gun)
		{
		 return gun * gunlukUcret;
		}
		///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
}
